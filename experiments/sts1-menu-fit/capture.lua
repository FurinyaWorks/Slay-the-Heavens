local F=dofile('tests/lua/support/game_ui_fixture.lua')
local V=dofile('scripts/official-assets-preview.lua')
local cursor={CursorEnter='enter',CursorDown='down',CursorUp='up',CursorExit='exit',CursorEndDrag='endDrag'}
local ui,root=F.fixture(nil,function()return true end,nil,cursor)
local menu=root:GetChild('menuPanel')
local start=menu:GetChild('start');local hit=start:GetChild('hit')
assert(not menu:GetChild('continueRun').visible)
for _,size in ipairs({{1280,720},{1920,1080},{1560,720},{2400,1080}})do
 ui:resize(size[1],size[2]);ui:refresh()
 assert(start.x==-464 and start.y==-114 and hit.size[1]==208 and hit.size[2]==48)
 assert(not menu:GetChild('continueRun').visible)
end
print('MENU_VIEWPORT 1280x720 1920x1080 1560x720 2400x1080 stable native input frames')
V.capture('menu-normal',ui,root,'Shipped Lua UI, fresh session, native-contract fixture')
hit.listeners.enter({touchId=1});ui:update(.2)
assert(start:GetChild('v25MenuFace'):GetChild('hover').visible)
V.capture('menu-hover',ui,root,'Real native CursorEnter receiver')
hit.listeners.down({touchId=1});ui:update(.05)
assert(start:GetChild('v25MenuFace'):GetChild('pressed').visible)
V.capture('menu-pressed',ui,root,'Real native CursorDown receiver')
hit.listeners.exit({touchId=1});ui:update(.2)
assert(ui:openExit())
assert(start:GetChild('v25MenuFace'):GetChild('disabled').visible)
V.capture('menu-disabled',ui,root,'Existing exit modal disables background menu via real GameUI refresh')
assert(ui:closeExit())
assert(F.start(ui));local run=ui.run
assert(ui:openMenu() and ui:returnToMainMenu())
assert(ui.sessionPaused and menu:GetChild('continueRun').visible)
V.capture('menu-continue',ui,root,'Existing paused live session; Run identity preserved')
assert(ui:continueRun() and ui.run==run and ui.mode~='menu')
print('MENU_ASSERTIONS four states, disabled input, fresh/paused continue and Run identity passed')
V.print()
