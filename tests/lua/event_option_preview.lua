local H=dofile('tests/helpers/act2_event_ui.lua')
local Theme=require('abyss_theme')
local event,card,relic='eventView/','eventView/previewCard','eventView/previewRelic'
local delay=Theme.layout.statusInfo.delay
local reference=Theme.layout.nativeNode.event.reference
local function colour(value,ink)
 return string.format('<color=#%02X%02X%02X>%s</color>',ink.r,ink.g,ink.b,value)
end
local function openNest(options)
 local run,map=H.fixture('nest')
 local ui,get,shown,click=H.setup(run,map,options)
 ui.presentation=require('abyss_character_presentation').prepare(ui.presentation,run.data)
 assert(click(event..'option1'))
 return run,map,ui,get,shown,click
end

H.test('Nest formats each consequence once and the entire option previews instantly without settling',function()
 local run,map,ui,get,shown,click=openNest()
 local before,mapBefore=H.snapshot(run),H.Copy(map)
 local copy=reference and '/title' or '/description'
 local title=get(event..'option2'..copy).text
 local reward,cost=reference and reference.rewardInk or Theme.color.positive,reference and reference.costInk or Theme.color.dangerText
 local _,names=title:gsub('仪式匕首','');assert(names==1,'Ritual Dagger should appear once: '..title)
 assert(title:find(colour('获得',reward)..'「仪式匕首」。',1,true),title)
 assert(title:find(colour('受到6点普通伤害。',cost),1,true),title)
 assert(get(event..'option1'..copy).text:find(colour('获得99金币。',reward),1,true))
 local dagger,gold=get(event..'option2/hit'),get(event..'option1/hit')
 dagger:emit('enter',1)
 assert(shown(card),'no immediate desktop face')
 assert(get(card..'/name').text:find('仪式匕首',1,true))
 assert(get(card..'/description').text:find('15',1,true))
 assert(get(card).y-Theme.layout.card.size[2]/2>=-360)
 gold:emit('enter',1);dagger:emit('exit',1)
 assert(not shown(card),'switching off a preview target left the card visible')
 dagger:emit('enter',1);dagger:emit('exit',1);assert(not shown(card))
 dagger:emit('enter',1);ui:setVisible(false);assert(not shown(card))
 H.same(run,before);H.same(map,mapBefore)
 ui:setVisible(true);assert(click(event..'option2'));H.eq(run.hp,before.hp-6)
end)

H.test('event touch holds retain the preview on release and consume only that gesture',function()
 local run,map,ui,get,shown,click=openNest({touchScreen=function()return true end})
 local before,mapBefore=H.snapshot(run),H.Copy(map)
 local dagger,gold=get(event..'option2/hit'),get(event..'option1/hit')
 dagger:emit('enter',7);assert(not shown(card))
 dagger:emit('down',7);ui:update(delay-0.01);assert(not shown(card))
 dagger:emit('endDrag',7);ui:update(delay);assert(not shown(card))
 dagger:emit('down',8);ui:update(delay);assert(shown(card))
 dagger:emit('up',8);assert(shown(card))
 local selected,reason=dagger:emit('click',8)
 H.eq(selected,false);H.eq(reason,'inspected');assert(shown(card))
 H.eq(dagger:emit('click',8),false)
 H.same(run,before);H.same(map,mapBefore)
 gold:emit('down',9);assert(not shown(card));gold:emit('endDrag',9)
 assert(click(event..'option2',10));assert(not shown(card));H.eq(run.hp,before.hp-6)
end)

H.test('cover during an unfinished hold cancels the preview and the release',function()
 local covered=false
 local run,_,ui,get,shown,click=openNest({touchScreen=function()return true end,inputCovered=function()return covered end})
 local before=H.snapshot(run)
 local hit=get(event..'option2/hit')
 hit:emit('down',7);ui:update(delay-0.01)
 covered=true;ui:update(0.02)
 covered=false;ui:update(1)
 hit:emit('up',7);H.eq(hit:emit('click',7),false)
 assert(not shown(card));H.same(run,before)
 assert(click(event..'option2',7));H.eq(run.hp,before.hp-6)
end)

